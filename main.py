import hashlib

MDP_SIZE = 23 # the length of the final password generated by default
CAR = (
        '!@#$%^&*()'
        '1234567890'
        'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
        'abcdefghijklmnopqrstuvwxyz'
    ) # list of characters that will make up the generated password

def deterministic_hash(value) : # Hashage: Converts a string to an integer
    return int(hashlib.sha256(value.encode('utf-8')).hexdigest(), 16)

def generate_password(identifier, password, mdp_size=MDP_SIZE, car=CAR):
    if not identifier:
        raise ValueError("The ID cannot be empty.")

    if not password:
        raise ValueError("The master password cannot be empty.")

    if mdp_size <= 0:
        raise ValueError("The length must be positive.")

    N = len(car) # len = 72 by default

    # hashage
    hash_id = abs(deterministic_hash(identifier))
    hash_wp = abs(deterministic_hash(password))

    # manipulating the hashed ID and password to create a unique large integer
    hash_wp = hash_wp * 2 + hash_id ** 2
    while len(str(abs(hash_wp))) < mdp_size * 10 :
        hash_wp = hash_wp * 2 + hash_id ** 2

    # Using the result to create a size-2 index list: 24908273 -> [24, 90, 82, 73]
    tab_wp = [int(str(hash_wp)[i:i+2]) for i in range(len(str(hash_wp))-(mdp_size*2), len(str(hash_wp)), 2)]

    # Create a new password using the hint list to select characters from the 'car' list
    new_wp = ""
    for i in tab_wp :
        new_wp += str(car[i % N])

    # Final password
    return new_wp[:mdp_size]


if __name__ == "__main__":
    identifier = input("Identifier : ")
    password = input("PassWord : ")

    print("Your password: ", generate_password(identifier, password))
